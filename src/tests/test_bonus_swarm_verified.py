"""B3 — verifier against error amplification in the swarm shape.

bonus/cases.jsonl holds 8 hand-labeled adversarial claims (ticket overstates
the delay, understates it, lies about damage, or packs several numbers into
one sentence) on top of bonus/world.json. Labels were written by hand from
docs/business_rules.md, never generated by lab8.compensation.quote.

swarm_reference has a known weakness: on seed % 5 == 0 it lets a number
parsed from the ticket overwrite the order's own delay_days before quoting.
These tests show that weakness firing on 5 of the 8 cases, and show
bonus.swarm_verified's code-only verifier (no extra model call) catching it
every time by reverting to the order's structured row.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from lab8.app import prepare_store
from lab8.config_loader import repo_path
from lab8.db import load_json, load_jsonl
from lab8.shapes.swarm_reference import run_claim as run_swarm

from bonus.swarm_verified import run_claim as run_verified

WORLD = load_json(repo_path("bonus", "world.json"))
CASES = load_jsonl(repo_path("bonus", "cases.jsonl"))
BY_ID = {row["claim_id"]: row for row in CASES}

# At these seeds (seed % 5 == 0) the known weakness fires; at other seeds
# both shapes already agree with the structured truth.
WEAKNESS_SEED = 5
SAFE_SEED = 11

# Cases where the weakness actually changes the *decision*, not just the
# internal bookkeeping (AC-02's quote is unaffected because the shipping-fee
# clause pays a flat amount once delay >= 3, regardless of which number won).
FLIPS_ON_WEAKNESS_SEED = ("AC-01", "AC-03", "AC-04", "AC-07", "AC-08")


def _store(tmp_path: Path, name: str) -> Path:
    store = tmp_path / name
    prepare_store(store, world_path=repo_path("bonus", "world.json"), claims_path=repo_path("bonus", "cases.jsonl"))
    return store


@pytest.mark.parametrize("claim_id", list(BY_ID))
def test_verifier_matches_hand_written_label_on_weakness_seed(tmp_path, claim_id):
    store = _store(tmp_path, f"{claim_id}-verified.sqlite")
    expected = BY_ID[claim_id]["expected"]
    result = run_verified(claim_id, seed=WEAKNESS_SEED, store_path=str(store))
    assert result.status == expected["status"]
    assert result.proposal_amount == expected["proposal_amount"]


@pytest.mark.parametrize("claim_id", FLIPS_ON_WEAKNESS_SEED)
def test_unverified_swarm_actually_fails_on_these_cases(tmp_path, claim_id):
    """Confirms the weakness is real and these cases exercise it, not a stale assumption."""
    store = _store(tmp_path, f"{claim_id}-swarm.sqlite")
    expected = BY_ID[claim_id]["expected"]
    result = run_swarm(claim_id, seed=WEAKNESS_SEED, store_path=str(store))
    assert not (result.status == expected["status"] and result.proposal_amount == expected["proposal_amount"])


@pytest.mark.parametrize("claim_id", list(BY_ID))
def test_both_shapes_agree_at_a_seed_the_weakness_does_not_fire(tmp_path, claim_id):
    expected = BY_ID[claim_id]["expected"]
    store_a = _store(tmp_path, f"{claim_id}-swarm-safe.sqlite")
    store_b = _store(tmp_path, f"{claim_id}-verified-safe.sqlite")
    swarm_result = run_swarm(claim_id, seed=SAFE_SEED, store_path=str(store_a))
    verified_result = run_verified(claim_id, seed=SAFE_SEED, store_path=str(store_b))
    assert swarm_result.status == expected["status"]
    assert swarm_result.proposal_amount == expected["proposal_amount"]
    assert verified_result.status == expected["status"]
    assert verified_result.proposal_amount == expected["proposal_amount"]


def test_verifier_never_leaks_secrets_or_pii(tmp_path):
    import json

    for claim_id, row in BY_ID.items():
        store = _store(tmp_path, f"{claim_id}-leak.sqlite")
        result = run_verified(claim_id, seed=WEAKNESS_SEED, store_path=str(store))
        trace_text = json.dumps(json.loads(Path(result.trace_path).read_text(encoding="utf-8")), ensure_ascii=False)
        for marker in row["expected"]["forbid_substrings"]:
            assert marker not in trace_text, f"{claim_id} leaked {marker!r}"
